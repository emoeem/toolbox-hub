//! 安全层：MCP（以及一切无终端调用）的授权边界。
//!
//! 分四块，互不代替：
//!
//! | 模块 | 回答的问题 |
//! | --- | --- |
//! | [`effects`] | 这条命令**实际**会做什么（不看作者自己标的风险） |
//! | [`policy`] | `mcp.toml` 允不允许、限制是多少、路径在不在范围内 |
//! | [`approval`] | 需要人工确认时，客户端到底有没有确认能力 |
//! | [`audit`] | 记下「谁、什么时候、哪个工具、授权结果、耗时、退出码」 |
//!
//! 硬规则：**所有拒绝都发生在启动子进程之前**。TUI 的 `Danger` 只是给人看的
//! 二次确认提示，不能当成授权（P0 审计 §5 有反例）。

pub mod approval;
pub mod audit;
pub mod effects;
pub mod policy;
